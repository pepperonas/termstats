"""Write native/src/themes.rs from termstats/theme.py.

The native core must paint the same colours as the Python dashboard. Rather than port the
ramp mathematics and hope the two stay equal, the tables are GENERATED: for every theme a
256-entry ramp, the dimmed ramp for secondary segments, and the tones. Run after any change
to a theme:  python tools/gen_native_themes.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from termstats import theme as T  # noqa: E402

N = 256


def rgb_u32(rgb):
    return "0x%02x%02x%02x" % (int(rgb[0]), int(rgb[1]), int(rgb[2]))


def table(values):
    rows = []
    for i in range(0, len(values), 8):
        rows.append("        " + ", ".join(values[i:i + 8]) + ",")
    return "\n".join(rows)


def render():
    """The text of native/src/themes.rs for the themes as they are now."""
    out = ["// GENERATED by tools/gen_native_themes.py from termstats/theme.py - do not edit.",
           "",
           "pub struct Theme {",
           "    pub name: &'static str,",
           "    pub ramp: [u32; 256],",
           "    pub dim: [u32; 256],",
           "    pub text: u32, pub soft: u32, pub label: u32, pub muted: u32, pub faint: u32,",
           "    pub track: u32, pub border: u32, pub accent: u32,",
           "    pub wordmark_bg: u32, pub wordmark_fg: u32, pub bg: u32,",
           "}",
           "",
           f"pub const DEFAULT_THEME: &str = \"{T.DEFAULT_THEME}\";",
           "",
           "pub static THEMES: &[Theme] = &["]
    for name, th in T.THEMES.items():
        ramp = T.Ramp(th.stops)
        colours = [ramp.rgb(i / (N - 1)) for i in range(N)]
        dims = [T.rgb_of(T.dim_hex(c)) for c in colours]
        tone = lambda h: rgb_u32(T.rgb_of(h))  # noqa: E731
        out += ["    Theme {",
                f"        name: \"{name}\",",
                "        ramp: [", table([rgb_u32(c) for c in colours]), "        ],",
                "        dim: [", table([rgb_u32(c) for c in dims]), "        ],",
                f"        text: {tone(th.text)}, soft: {tone(th.soft)}, label: {tone(th.dim)}, "
                f"muted: {tone(th.muted)}, faint: {tone(th.faint)},",
                f"        track: {tone(th.track)}, border: {tone(th.border)}, accent: {tone(th.accent)},",
                f"        wordmark_bg: {tone(th.wordmark_bg)}, wordmark_fg: {tone(th.wordmark_fg)}, bg: {tone(th.bg)},",
                "    },"]
    out += ["];", ""]
    out += big_font()
    return "\n".join(out)


def big_font():
    """The headline digits of the microphone screens: the same 3x5 shapes as theme.BIG_FONT,
    "#" a filled square and "." an empty one, painted by the core in its bar glyph."""
    out = ["// The five-row font of the level and tempo headlines (theme.BIG_FONT).",
           f"pub const BIG_DIGIT_ROWS: usize = {T.BIG_DIGIT_ROWS};",
           f"pub const BIG_DIGIT_SCALE: usize = {T.BIG_DIGIT_SCALE};",
           f"pub const BIG_DIGIT_GAP: usize = {T.BIG_DIGIT_GAP};",
           f"pub const BIG_DIGIT_MIN_ROWS: usize = {T.BIG_DIGIT_MIN_ROWS};",
           f"pub const METRO_W: usize = {T.METRO_W};",
           "",
           f"pub static BIG_FONT: &[(char, [&str; {T.BIG_DIGIT_ROWS}])] = &["]
    for ch, rows in T.BIG_FONT.items():
        cells = ", ".join(f'"{r}"' for r in rows)
        out.append(f"    ({ch!r}, [{cells}]),")
    out += ["];", ""]
    return out


TARGET = ROOT / "native" / "src" / "themes.rs"


def main():
    TARGET.write_text(render(), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(T.THEMES)} themes")


if __name__ == "__main__":
    main()

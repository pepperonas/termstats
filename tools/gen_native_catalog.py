"""Write native/src/catalog.rs from catalog/hardware.json.

The catalogue - which computers exist, what they cost, how fast their chips are - is data
that ages, so it lives in ONE reviewed JSON file with a source and a date on every entry.
The native core has no JSON parser and should not get one for a file that changes a few
times a year: this script turns the file into Rust tables. Run after any change:

    python tools/gen_native_catalog.py

A device variant without a price, or a chip without CPU scores, cannot be recommended and is
left out (the script says which); tests/test_catalog.py keeps the JSON itself honest.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "catalog" / "hardware.json"
TARGET = ROOT / "native" / "src" / "catalog.rs"

HEAD = '''// GENERATED by tools/gen_native_catalog.py from catalog/hardware.json - do not edit.

pub struct Chip {
    pub id: &'static str,
    pub name: &'static str,
    /// What the machine itself calls the chip (sysctl / cpuinfo), to recognise the current one.
    pub brand: &'static str,
    pub perf_cores: u8,
    pub eff_cores: u8,
    /// Geekbench 6 single-core, multi-core and GPU scores. gpu is 0 where none is known.
    pub single: u32,
    pub multi: u32,
    pub gpu: u32,
}

pub struct Step {
    pub gb: u32,
    pub plus_eur: u32,
}

pub struct Variant {
    pub chip: &'static str,
    pub base_price_eur: u32,
    pub ram: &'static [Step],
    pub ssd: &'static [Step],
}

pub struct Device {
    pub id: &'static str,
    pub vendor: &'static str,
    pub name: &'static str,
    /// "laptop", "desktop" or "all-in-one".
    pub form: &'static str,
    /// "macOS" or "Linux".
    pub os: &'static str,
    pub fanless: bool,
    pub variants: &'static [Variant],
    pub source: &'static str,
    /// The prices were read from the manufacturer's own page.
    pub verified: bool,
}
'''


def rs(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def brand_of(chip):
    return chip.get("brand") or chip["name"].split(" (")[0]


def steps(options, base_gb):
    """Sorted, deduplicated upgrade steps; the base size is always there at +0."""
    seen = {}
    for option in options or []:
        if option.get("gb") is not None and option.get("plus_eur") is not None:
            seen[int(option["gb"])] = int(option["plus_eur"])
    if base_gb is not None:
        seen.setdefault(int(base_gb), 0)
    return sorted(seen.items())


def usable(data):
    """(chips, devices, skipped): what can be recommended, and what was left out and why."""
    skipped = []
    chips = {}
    for chip_id, chip in data["chips"].items():
        if not chip.get("single") or not chip.get("multi"):
            skipped.append(f"chip {chip_id}: no CPU scores")
            continue
        chips[chip_id] = chip
    devices = []
    for device in data["devices"]:
        variants = []
        for variant in device.get("variants", []):
            label = f"{device['id']} / {variant.get('chip')}"
            if variant.get("chip") not in chips:
                skipped.append(f"{label}: chip has no scores")
            elif not variant.get("base_price_eur"):
                skipped.append(f"{label}: no price")
            elif not variant.get("base_ram_gb") or not variant.get("base_ssd_gb"):
                skipped.append(f"{label}: no base memory or storage")
            else:
                variants.append(variant)
        if variants:
            devices.append((device, variants))
        else:
            skipped.append(f"device {device['id']}: no usable variant")
    return chips, devices, skipped


def render(data=None):
    """The text of native/src/catalog.rs for the catalogue as it is now."""
    data = json.loads(SOURCE.read_text(encoding="utf-8")) if data is None else data
    chips, devices, _skipped = usable(data)
    out = [HEAD, f"pub const STAND: &str = {rs(data['stand'])};", "", "pub static CHIPS: &[Chip] = &["]
    for chip_id, chip in chips.items():
        out.append(f"    Chip {{ id: {rs(chip_id)}, name: {rs(chip['name'])}, brand: {rs(brand_of(chip))}, "
                   f"perf_cores: {int(chip.get('perf_cores') or 0)}, eff_cores: {int(chip.get('eff_cores') or 0)}, "
                   f"single: {int(chip['single'])}, multi: {int(chip['multi'])}, gpu: {int(chip.get('gpu') or 0)} }},")
    out += ["];", "", "pub static DEVICES: &[Device] = &["]
    for device, variants in devices:
        out.append(f"    Device {{ id: {rs(device['id'])}, vendor: {rs(device['vendor'])}, name: {rs(device['name'])}, "
                   f"form: {rs(device['form'])}, os: {rs(device['os'])}, fanless: {'true' if device.get('fanless') else 'false'}, "
                   f"source: {rs(device.get('source') or '')}, verified: {'true' if device.get('verified') else 'false'}, variants: &[")
        for variant in variants:
            ram = ", ".join(f"Step {{ gb: {gb}, plus_eur: {eur} }}" for gb, eur in steps(variant.get("ram_options"), variant["base_ram_gb"]))
            ssd = ", ".join(f"Step {{ gb: {gb}, plus_eur: {eur} }}" for gb, eur in steps(variant.get("ssd_options"), variant["base_ssd_gb"]))
            out.append(f"        Variant {{ chip: {rs(variant['chip'])}, base_price_eur: {int(variant['base_price_eur'])}, "
                       f"ram: &[{ram}], ssd: &[{ssd}] }},")
        out.append("    ] },")
    out += ["];", ""]
    return "\n".join(out)


def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    chips, devices, skipped = usable(data)
    TARGET.write_text(render(data), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(chips)} chips, {len(devices)} devices, "
          f"{sum(len(v) for _d, v in devices)} variants (catalogue of {data['stand']})")
    for line in skipped:
        print(f"  left out - {line}", file=sys.stderr)


if __name__ == "__main__":
    main()

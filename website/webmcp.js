// WebMCP tools: lets an AI agent in the browser ask this page for facts and actions directly instead of
// scraping it (https://developer.chrome.com/docs/ai/webmcp). Only registered where the browser offers
// `modelContext`; everywhere else this file does nothing. All data comes from the same places the page
// uses — latest.json and changelog.md on this origin — so tools and page can never disagree.
(function () {
  'use strict';

  var mc = (typeof document !== 'undefined' && document.modelContext) ||
    (typeof navigator !== 'undefined' && navigator.modelContext);
  if (!mc || typeof mc.registerTool !== 'function') return;

  // Facts from site.json (generated by build.py).
  var FACTS = {
    "name": "termstats",
    "summary": "termstats is a free, open-source (MIT) system dashboard for the terminal. It shows CPU load per core, memory and swap, network rates, disks, the busiest processes and live history charts, and adapts to the size and abilities of the terminal. On macOS and Linux a native binary written in Rust draws the live dashboard with about 0.3 % of one CPU core and 7 MB of memory; the Python program adds microphone screens (spectrum analyser, tempo, level), a scripted demo and snapshots, and runs on Windows too, where it ships as a single termstats.exe. On macOS and Linux termstats can record what the machine does in a local log and, after 14 days, recommend a computer that fits. It needs no account and no configuration file and never contacts the network.",
    "requirements": {
      "macos": "macOS · Apple silicon",
      "linux": "Linux · x86-64 · static binary",
      "windows": "Windows 10/11 · x64 · no Python needed",
      "macos-intel": "macOS · Intel",
      "linux-arm64": "Linux · ARM64 (Raspberry Pi 4/5, ARM servers)",
      "python": "Python 3.9+ · every platform"
    },
    "platforms": [
      "macOS",
      "Linux",
      "Windows",
      "Raspberry Pi",
      "SSH"
    ],
    "features": [
      "Live dashboard: CPU per core, memory and swap, network rates, disks, processes",
      "History charts for CPU and network, drawn with braille characters",
      "Native Rust binary for macOS and Linux: about 0.3 % of one CPU core, 7 MB of memory",
      "Single termstats.exe for Windows, no Python needed",
      "Microphone screens: 28-band spectrum analyser, tempo (BPM), level (dB), level and tempo side by side",
      "Six colour themes; fallbacks from 24-bit colour to monochrome and from braille to ASCII; NO_COLOR honoured",
      "History recorder as a background service (macOS, Linux): one line per minute in a local log",
      "Computer recommendation after 14 days of history, in three tiers, with a Linux alternative",
      "Snapshot output when piped; a scripted demo machine",
      "No configuration file, no account, no network access"
    ],
    "limits": [
      "The native binary, the history recorder and the recommendation run on macOS and Linux only; Windows gets the Python program as termstats.exe.",
      "The native binary has no microphone screens, no demo and no ASCII or block fallbacks - those are in the Python program.",
      "termstats is not on PyPI, Homebrew or winget; it is distributed through GitHub Releases and this page.",
      "The files are not code-signed or notarised: macOS quarantines a browser download and Windows SmartScreen may ask once.",
      "It watches one machine in one terminal; it is not a monitoring server and keeps no remote history.",
      "The recommendation uses list prices and benchmark scores from a catalogue shipped with each release; it does not check special requirements such as particular software or ports."
    ],
    "targets": [
      "macos",
      "linux",
      "windows",
      "macos-intel",
      "linux-arm64",
      "python"
    ],
    "signing": [],
    "links": {
      "page": "https://termstats.celox.io/",
      "download": "https://termstats.celox.io/download",
      "latest": "https://termstats.celox.io/latest.json",
      "markdown": "https://termstats.celox.io/index.md",
      "changelog": "https://termstats.celox.io/changelog.md",
      "skill": "https://termstats.celox.io/skills/get-termstats/SKILL.md",
      "source": "https://github.com/pepperonas/termstats",
      "licence": "https://github.com/pepperonas/termstats/blob/main/LICENSE"
    }
  };
  var SITE = FACTS.links.page.replace(/\/$/, '');
  var LANGS = ["en", "de", "es", "it", "fr"];

  function latest(signal) {
    return fetch('/latest.json', { cache: 'no-cache', signal: signal }).then(function (r) {
      if (!r.ok) throw new Error('latest.json: HTTP ' + r.status);
      return r.json();
    });
  }
  function json(v) { return JSON.stringify(v, null, 2); }
  var READ = { readOnlyHint: true };

  var tools = [
    {
      name: 'get_app_facts',
      description: 'What termstats is: a one-paragraph summary, requirements, supported platforms, ' +
        'features, limits and the important links (download, source, changelog, licence).',
      inputSchema: { type: 'object', properties: {}, additionalProperties: false },
      annotations: READ,
      execute: function () { return Promise.resolve(json(FACTS)); }
    },
    {
      name: 'get_latest_release',
      description: 'The newest release of termstats: version, publication date, release notes URL ' +
        'and every file with its download URL, size in bytes and SHA-256.',
      inputSchema: { type: 'object', properties: {}, additionalProperties: false },
      annotations: READ,
      execute: function (_input, opts) {
        return latest(opts && opts.signal).then(function (d) {
          return json({ version: d.version, published: d.published, notes: d.notes, assets: d.assets ||
            [{ target: FACTS.targets[0], name: d.name, url: d.url, size: d.size, sha256: d.sha256 }] });
        });
      }
    },
    {
      name: 'get_download_url',
      description: 'The direct download URL of the newest termstats file for a platform (macos, linux, windows, macos-intel, linux-arm64, python), plus ' +
        'the stable link that always redirects to the newest file.',
      inputSchema: {
        type: 'object',
        properties: { platform: { type: 'string', enum: FACTS.targets, description: 'Target platform; default: ' + FACTS.targets[0] + '.' } },
        additionalProperties: false
      },
      annotations: READ,
      execute: function (input, opts) {
        return latest(opts && opts.signal).then(function (d) {
          var assets = d.assets || [{ target: FACTS.targets[0], name: d.name, url: d.url, size: d.size }];
          var want = (input && input.platform) || assets[0].target;
          var a = assets.filter(function (x) { return x.target === want; })[0] || assets[0];
          return json({ version: d.version, platform: a.target, file: a.name, url: a.url, size: a.size,
            stable_link: SITE + '/download/' + a.target });
        });
      }
    },
    {
      name: 'get_checksums',
      description: 'How to verify a downloaded termstats file: the SHA-256 of every file of the newest release ' +
        'and the fixed signing facts.',
      inputSchema: { type: 'object', properties: {}, additionalProperties: false },
      annotations: READ,
      execute: function (_input, opts) {
        return latest(opts && opts.signal).then(function (d) {
          var assets = d.assets || [{ name: d.name, sha256: d.sha256 }];
          return json({ version: d.version,
            files: assets.map(function (a) { return { name: a.name, sha256: a.sha256 }; }),
            signing: FACTS.signing });
        });
      }
    },
    {
      name: 'get_changelog',
      description: 'The most recent entries of the termstats changelog as Markdown.',
      inputSchema: {
        type: 'object',
        properties: { versions: { type: 'integer', minimum: 1, maximum: 10, description: 'How many versions (default 3).' } },
        additionalProperties: false
      },
      annotations: READ,
      execute: function (input, opts) {
        var n = Math.min(10, Math.max(1, (input && input.versions) || 3));
        return fetch('/changelog.md', { cache: 'no-cache', signal: opts && opts.signal }).then(function (r) {
          if (!r.ok) throw new Error('changelog.md: HTTP ' + r.status);
          return r.text();
        }).then(function (md) {
          var parts = md.split(/\n(?=## \[)/).slice(1).filter(function (s) { return !/^## \[Unreleased\]\s*$/.test(s.trim()); });
          return parts.slice(0, n).join('\n').trim();
        });
      }
    },
    {
      name: 'set_page_language',
      description: 'Show this page in another language (English, German, Spanish, Italian or French).',
      inputSchema: {
        type: 'object',
        properties: { language: { type: 'string', enum: LANGS, description: 'ISO 639-1 code.' } },
        required: ['language'],
        additionalProperties: false
      },
      annotations: { readOnlyHint: false },
      execute: function (input) {
        if (LANGS.indexOf(input.language) < 0) throw new Error('unsupported language: ' + input.language);
        if (typeof window.SITE_setLanguage === 'function') window.SITE_setLanguage(input.language);
        return Promise.resolve('Page language set to ' + input.language + '.');
      }
    }
  ];

  tools.forEach(function (t) {
    try { mc.registerTool(t); } catch (e) { /* a browser with an older WebMCP shape: skip that tool */ }
  });
})();
